check('table_add_row_column', 'await window.__livemark.handlers.get("editor.command")({command:"table.rowAfter"});await window.__livemark.handlers.get("editor.command")({command:"table.columnAfter"});return {ok:document.querySelectorAll("table tr").length===4&&document.querySelector("table tr").children.length===3,rows:document.querySelectorAll("table tr").length};')
check('table_delete_and_undo', 'await window.__livemark.handlers.get("editor.command")({command:"table.delete"});const gone=!document.querySelector("table");await window.__livemark.handlers.get("editor.command")({command:"undo"});return {ok:gone&&!!document.querySelector("table")};')
