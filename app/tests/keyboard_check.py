check('duplicate_read_idempotent', 'const before=await window.__livemark.handlers.get("file.save")();await window.__livemark.handlers.get("file.read")({content:"",documentID:"paste",generation:1});const after=await window.__livemark.handlers.get("file.save")();return {ok:before.content===after.content&&after.dirty};')
load('', 'images')
check('image_clipboard_waits_before_save', 'const bytes=Uint8Array.from(atob("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aD3sAAAAASUVORK5CYII="),c=>c.charCodeAt(0));const clip=new DataTransfer();clip.items.add(new File([bytes],"pixel.png",{type:"image/png"}));document.querySelector(".ProseMirror").dispatchEvent(new ClipboardEvent("paste",{clipboardData:clip,bubbles:true,cancelable:true}));const s=await window.__livemark.handlers.get("file.save")();return {ok:s.content.includes("data:image/png;base64,")&&s.dirty&&!!document.querySelector(".ProseMirror img[data-source]"),length:s.content.length};')
(OUT/'keyboard_results.json').write_text(json.dumps(results,ensure_ascii=False,indent=2))
