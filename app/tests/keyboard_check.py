cli('type_text', '```javascript')
cli('press_key', 'Enter')
cli('type_text', 'const answer = 42;')
cli('press_key', 'Meta+Enter')
cli('type_text', '代码之后')
check('code_fence_and_exit', 'const s=await window.__livemark.handlers.get("file.save")();return {ok:s.content.includes("```javascript")&&s.content.includes("const answer = 42;")&&s.content.includes("代码之后"),content:s.content};')
