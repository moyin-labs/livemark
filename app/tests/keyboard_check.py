load('', 'table')
evaluate('await window.__livemark.handlers.get("editor.command")({command:"table",rows:3,cols:2});document.querySelector(".ProseMirror").focus();const cell=document.querySelector("th p");const range=document.createRange();range.setStart(cell,0);range.collapse(true);const selection=window.getSelection();selection.removeAllRanges();selection.addRange(range);document.dispatchEvent(new Event("selectionchange"));return {ok:true};')
